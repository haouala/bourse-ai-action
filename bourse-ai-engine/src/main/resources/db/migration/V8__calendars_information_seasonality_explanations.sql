CREATE TABLE market_calendars (
 code VARCHAR(40) PRIMARY KEY,
 zone_id VARCHAR(80) NOT NULL,
 coverage_start DATE NOT NULL,
 coverage_end DATE NOT NULL,
 source_url VARCHAR(1500) NOT NULL,
 updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (coverage_end>=coverage_start)
);
CREATE TABLE market_sessions (
 calendar_code VARCHAR(40) NOT NULL REFERENCES market_calendars(code),
 session_date DATE NOT NULL,
 opens_at TIMESTAMP WITH TIME ZONE,
 closes_at TIMESTAMP WITH TIME ZONE,
 reason VARCHAR(120) NOT NULL,
 source_url VARCHAR(1500) NOT NULL,
 updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(calendar_code,session_date),
 CHECK ((opens_at IS NULL AND closes_at IS NULL) OR (opens_at IS NOT NULL AND closes_at IS NOT NULL AND closes_at>opens_at))
);
CREATE TABLE asset_market_policies (
 asset_id BIGINT PRIMARY KEY REFERENCES assets(id),
 calendar_code VARCHAR(40) NOT NULL,
 delivery_grace_seconds INTEGER NOT NULL DEFAULT 180 CHECK (delivery_grace_seconds BETWEEN 0 AND 86400),
 trading_status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' CHECK (trading_status IN ('ACTIVE','HALTED')),
 status_reason VARCHAR(300),
 fx_max_age_seconds INTEGER NOT NULL DEFAULT 3600 CHECK (fx_max_age_seconds BETWEEN 60 AND 604800),
 updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
