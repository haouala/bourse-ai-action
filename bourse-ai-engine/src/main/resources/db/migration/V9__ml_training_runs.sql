-- Module 7: versioned, auditable ML direction-training reports.
-- Forecasts and prices are deliberately NOT produced by this module.
CREATE TABLE ml_training_runs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_id BIGINT NOT NULL REFERENCES assets(id),
 algorithm VARCHAR(80) NOT NULL,
 version VARCHAR(40) NOT NULL,
 horizon_sessions INTEGER NOT NULL CHECK(horizon_sessions IN (5,10,20)),
 feature_spec VARCHAR(300) NOT NULL,
 train_samples INTEGER NOT NULL CHECK(train_samples>=0),
 test_samples INTEGER NOT NULL CHECK(test_samples>=0),
 training_cutoff TIMESTAMP WITH TIME ZONE NOT NULL,
 last_test_time TIMESTAMP WITH TIME ZONE NOT NULL,
 direction_accuracy NUMERIC(12,8) NOT NULL CHECK(direction_accuracy BETWEEN 0 AND 1),
 baseline_accuracy NUMERIC(12,8) NOT NULL CHECK(baseline_accuracy BETWEEN 0 AND 1),
 brier_score NUMERIC(12,8) NOT NULL CHECK(brier_score BETWEEN 0 AND 1),
 baseline_brier NUMERIC(12,8) NOT NULL CHECK(baseline_brier BETWEEN 0 AND 1),
 status VARCHAR(32) NOT NULL CHECK(status IN ('RESEARCH_ONLY','BASELINE_NOT_BEATEN')),
 notes VARCHAR(1500) NOT NULL,
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_ml_runs_asset_recent ON ml_training_runs(asset_id,created_time DESC,id DESC);
