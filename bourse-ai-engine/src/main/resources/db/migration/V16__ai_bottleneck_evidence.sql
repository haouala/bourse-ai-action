-- Source-labeled analyst evidence; not an autonomous web claim.
CREATE TABLE ai_bottleneck_evidence (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_id BIGINT NOT NULL REFERENCES assets(id),
 signal_type VARCHAR(32) NOT NULL CHECK(signal_type IN ('SUPPLY_SHORTAGE','CAPACITY_EXPANSION','ORDER_BACKLOG','VALUATION_RISK','EXECUTION_RISK')),
 direction VARCHAR(10) NOT NULL CHECK(direction IN ('POSITIVE','NEGATIVE')),
 confidence VARCHAR(10) NOT NULL CHECK(confidence IN ('LOW','MEDIUM','HIGH')),
 source_url VARCHAR(1200) NOT NULL,
 summary VARCHAR(1500) NOT NULL,
 observed_date DATE NOT NULL,
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_bottleneck_source UNIQUE(asset_id,signal_type,source_url)
);
CREATE INDEX idx_bottleneck_asset_date ON ai_bottleneck_evidence(asset_id,observed_date DESC);
