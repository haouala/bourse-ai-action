-- Module 15: isolated paper accounts and immutable simulated fills.
CREATE TABLE paper_accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_name VARCHAR(80) NOT NULL UNIQUE,
 currency VARCHAR(3) NOT NULL CHECK (currency='USD'),
 initial_cash NUMERIC(24,8) NOT NULL CHECK(initial_cash>0),
 cash_balance NUMERIC(24,8) NOT NULL CHECK(cash_balance>=0),
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE paper_trades (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_id BIGINT NOT NULL REFERENCES paper_accounts(id),
 asset_id BIGINT NOT NULL REFERENCES assets(id),
 client_order_id VARCHAR(80) NOT NULL,
 side VARCHAR(4) NOT NULL CHECK(side IN ('BUY','SELL')),
 quantity NUMERIC(24,8) NOT NULL CHECK(quantity>0),
 simulated_price NUMERIC(24,10) NOT NULL CHECK(simulated_price>0),
 simulated_fee NUMERIC(24,8) NOT NULL CHECK(simulated_fee>=0),
 quote_time TIMESTAMP WITH TIME ZONE NOT NULL,
 executed_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_paper_client_order UNIQUE(account_id,client_order_id)
);
CREATE INDEX idx_paper_trades_account_asset ON paper_trades(account_id,asset_id,id);
