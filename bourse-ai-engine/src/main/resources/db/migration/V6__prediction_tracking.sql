-- Module 3: immutable forecast inputs with separately recorded outcomes.
-- Only server-side settlement can populate realized values.
CREATE TABLE prediction_records (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_id BIGINT NOT NULL REFERENCES assets(id),
 model_name VARCHAR(80) NOT NULL,
 model_version VARCHAR(80) NOT NULL,
 horizon_days INTEGER NOT NULL CHECK (horizon_days IN (7,30,90,180)),
 predicted_price NUMERIC(24,10) NOT NULL CHECK (predicted_price > 0),
 reference_price NUMERIC(24,10) NOT NULL CHECK (reference_price > 0),
 reference_time TIMESTAMP WITH TIME ZONE NOT NULL,
 predicted_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 target_time TIMESTAMP WITH TIME ZONE NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','EVALUATED')),
 realized_time TIMESTAMP WITH TIME ZONE,
 realized_price NUMERIC(24,10),
 signed_error_pct NUMERIC(16,6),
 absolute_error_pct NUMERIC(16,6),
 direction_correct BOOLEAN,
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT chk_prediction_outcome CHECK (
  (status='PENDING' AND realized_time IS NULL AND realized_price IS NULL AND signed_error_pct IS NULL AND absolute_error_pct IS NULL AND direction_correct IS NULL)
  OR (status='EVALUATED' AND realized_time IS NOT NULL AND realized_price>0 AND signed_error_pct IS NOT NULL AND absolute_error_pct IS NOT NULL AND direction_correct IS NOT NULL)
 )
);
CREATE INDEX idx_predictions_pending ON prediction_records(status,target_time);
CREATE INDEX idx_predictions_asset ON prediction_records(asset_id,predicted_at DESC);
