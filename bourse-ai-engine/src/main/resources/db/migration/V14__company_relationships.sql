-- Module 5: sourced, typed company relationships; not correlations or predictions.
CREATE TABLE company_relationships (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 from_asset_id BIGINT NOT NULL REFERENCES assets(id),
 to_asset_id BIGINT NOT NULL REFERENCES assets(id),
 relationship_type VARCHAR(40) NOT NULL CHECK(relationship_type IN
  ('SUPPLIES_TO','CUSTOMER_OF','COMPETES_WITH','PARTNER_OF','OWNS_STAKE_IN','SECTOR_PEER')),
 direction VARCHAR(16) NOT NULL CHECK(direction IN ('DIRECTED','BIDIRECTIONAL')),
 confidence VARCHAR(16) NOT NULL CHECK(confidence IN ('LOW','MEDIUM','HIGH')),
 evidence_url VARCHAR(1500) NOT NULL,
 evidence_summary VARCHAR(1000) NOT NULL,
 evidence_date DATE NOT NULL,
 valid_from DATE,
 valid_until DATE,
 status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','RETRACTED')),
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT ck_relationship_distinct CHECK(from_asset_id<>to_asset_id),
 CONSTRAINT ck_relationship_dates CHECK(valid_until IS NULL OR valid_from IS NULL OR valid_until>=valid_from),
 CONSTRAINT uq_relationship_evidence UNIQUE(from_asset_id,to_asset_id,relationship_type,evidence_url)
);
CREATE INDEX idx_relationship_from ON company_relationships(from_asset_id,status);
CREATE INDEX idx_relationship_to ON company_relationships(to_asset_id,status);
