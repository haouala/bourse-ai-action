CREATE TABLE research_alert_rules (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_id BIGINT NOT NULL REFERENCES assets(id),
 rule_type VARCHAR(30) NOT NULL CHECK(rule_type IN ('PRICE_ABOVE','PRICE_BELOW','RISK_SCORE_ABOVE')),
 threshold NUMERIC(24,8) NOT NULL CHECK(threshold>0),
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE research_alert_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 rule_id BIGINT NOT NULL REFERENCES research_alert_rules(id),
 observed_value NUMERIC(24,8) NOT NULL,
 observation_time TIMESTAMP WITH TIME ZONE NOT NULL,
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_alert_observation UNIQUE(rule_id,observation_time)
);
CREATE INDEX idx_alert_asset ON research_alert_rules(asset_id,enabled);
