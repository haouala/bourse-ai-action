ALTER TABLE market_candles ADD COLUMN close_time TIMESTAMP WITH TIME ZONE;
ALTER TABLE provider_price_observations ADD COLUMN close_time TIMESTAMP WITH TIME ZONE;

CREATE TABLE alpaca_history_progress (
    asset_id BIGINT PRIMARY KEY REFERENCES assets(id),
    next_date DATE NOT NULL
);

CREATE TABLE alpaca_import_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mode VARCHAR(16) NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE,
    status VARCHAR(16) NOT NULL,
    from_date DATE NOT NULL,
    to_date DATE NOT NULL,
    symbols INTEGER NOT NULL,
    observed INTEGER,
    inserted INTEGER,
    differences INTEGER,
    missing INTEGER,
    error_code VARCHAR(48)
);
CREATE INDEX idx_alpaca_runs_mode ON alpaca_import_runs(mode, id DESC);
