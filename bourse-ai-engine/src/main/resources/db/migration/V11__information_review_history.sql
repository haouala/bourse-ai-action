CREATE TABLE information_ai_reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 analysis_id BIGINT NOT NULL REFERENCES information_ai_analyses(id),
 decision VARCHAR(16) NOT NULL CHECK(decision IN ('APPROVED','REJECTED')),
 reason VARCHAR(1000) NOT NULL,
 event_groups_json TEXT NOT NULL,
 reviewed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
INSERT INTO information_ai_reviews(analysis_id,decision,reason,event_groups_json,reviewed_at)
 SELECT id,review_status,review_reason,'{}',reviewed_at FROM information_ai_analyses
 WHERE review_status IN ('APPROVED','REJECTED');
