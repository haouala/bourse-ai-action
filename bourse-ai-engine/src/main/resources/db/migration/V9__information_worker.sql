CREATE TABLE information_contents (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 item_id BIGINT NOT NULL REFERENCES information_items(id),
 content_hash VARCHAR(64) NOT NULL,
 body_text TEXT NOT NULL,
 scope VARCHAR(24) NOT NULL CHECK(scope IN ('SUMMARY_ONLY','ARTICLE_EXTRACT','TRANSCRIPT','PARTIAL_TRANSCRIPT')),
 content_url VARCHAR(1500) NOT NULL,
 extraction_method VARCHAR(80) NOT NULL,
 fetch_error VARCHAR(80),
 segments_json TEXT NOT NULL,
 fetched_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(item_id,content_hash)
);
CREATE TABLE information_ai_jobs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 item_id BIGINT NOT NULL REFERENCES information_items(id),
 model VARCHAR(100) NOT NULL,
 prompt_version VARCHAR(80) NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','RUNNING','SUCCEEDED','FAILED')),
 attempts INTEGER NOT NULL DEFAULT 0,
 lease_token VARCHAR(40),
 lease_until TIMESTAMP WITH TIME ZONE,
 next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
 content_id BIGINT REFERENCES information_contents(id),
 error_code VARCHAR(80),
 created_time TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_time TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(item_id,model,prompt_version)
);
CREATE INDEX idx_information_ai_due ON information_ai_jobs(status,next_attempt_at);
