CREATE TABLE assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    asset_type VARCHAR(16) NOT NULL,
    currency VARCHAR(3) NOT NULL
);
CREATE TABLE market_candles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id BIGINT NOT NULL REFERENCES assets(id),
    timeframe VARCHAR(8) NOT NULL,
    open_time TIMESTAMP WITH TIME ZONE NOT NULL,
    open_price NUMERIC(24, 10) NOT NULL,
    high_price NUMERIC(24, 10) NOT NULL,
    low_price NUMERIC(24, 10) NOT NULL,
    close_price NUMERIC(24, 10) NOT NULL,
    volume NUMERIC(28, 8) NOT NULL,
    provider VARCHAR(64) NOT NULL,
    CONSTRAINT uq_candle UNIQUE(asset_id, timeframe, open_time),
    CONSTRAINT ck_prices CHECK (open_price > 0 AND high_price > 0 AND low_price > 0 AND close_price > 0 AND volume >= 0),
    CONSTRAINT ck_ohlc CHECK (high_price >= open_price AND high_price >= close_price AND high_price >= low_price AND low_price <= open_price AND low_price <= close_price)
);
CREATE INDEX idx_market_candles_lookup ON market_candles(asset_id, timeframe, open_time DESC);
