-- Shared GDELT bulk checkpoint. No reset on application restart.
CREATE TABLE gdelt_bulk_runs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 method VARCHAR(16) NOT NULL CHECK(method IN ('NGRAMS','GKG')),
 batch_key VARCHAR(30) NOT NULL,
 status VARCHAR(16) NOT NULL CHECK(status IN ('RUNNING','SUCCESS','DEFERRED','FAILED')),
 attempts INT NOT NULL DEFAULT 0 CHECK(attempts>=0),
 inserted_count INT NOT NULL DEFAULT 0,
 matched_count INT NOT NULL DEFAULT 0,
 error_code VARCHAR(64),
 lease_until TIMESTAMP WITH TIME ZONE,
 next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_gdelt_bulk_batch UNIQUE(method,batch_key)
);
CREATE INDEX idx_gdelt_bulk_retry ON gdelt_bulk_runs(method,status,next_attempt_at);
CREATE TABLE gdelt_bulk_guard (id INT PRIMARY KEY CHECK(id=1));
