-- The row lock serializes reservations across application instances sharing this DB.
CREATE TABLE provider_quota_locks (
    provider VARCHAR(40) PRIMARY KEY,
    blocked_until TIMESTAMP WITH TIME ZONE,
    created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
INSERT INTO provider_quota_locks(provider) VALUES ('TWELVE_DATA'), ('EODHD'), ('FMP');

-- Keep reservations even when the HTTP request or the enclosing import fails.
-- URLs, API keys and remote error bodies must never be stored here.
CREATE TABLE provider_api_calls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR(40) NOT NULL REFERENCES provider_quota_locks(provider),
    reserved_at TIMESTAMP WITH TIME ZONE NOT NULL,
    credits INTEGER NOT NULL CHECK (credits > 0),
    created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_provider_api_calls_window ON provider_api_calls(provider, reserved_at);
