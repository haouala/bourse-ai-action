CREATE TABLE market_news (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_id BIGINT NOT NULL REFERENCES assets(id),
 source VARCHAR(120) NOT NULL,
 title VARCHAR(1500) NOT NULL,
 url VARCHAR(2000) NOT NULL,
 published_time TIMESTAMP WITH TIME ZONE,
 seen_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 sentiment_score INTEGER,
 sentiment_method VARCHAR(64),
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_news_asset_url UNIQUE(asset_id, url)
);
CREATE INDEX idx_news_asset_published ON market_news(asset_id, published_time DESC);

CREATE TABLE financial_facts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_id BIGINT NOT NULL REFERENCES assets(id),
 concept VARCHAR(120) NOT NULL,
 value NUMERIC(30, 4) NOT NULL,
 unit VARCHAR(24) NOT NULL,
 period_start DATE,
 period_end DATE NOT NULL,
 filed_date DATE NOT NULL,
 form_type VARCHAR(20) NOT NULL,
 accession_number VARCHAR(32) NOT NULL,
 source VARCHAR(40) NOT NULL,
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_financial_fact UNIQUE(asset_id, concept, accession_number, period_end, unit)
);
CREATE INDEX idx_facts_lookup ON financial_facts(asset_id, concept, filed_date DESC);

CREATE TABLE import_jobs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_symbol VARCHAR(40) NOT NULL,
 provider VARCHAR(50) NOT NULL,
 dataset VARCHAR(50) NOT NULL,
 status VARCHAR(20) NOT NULL,
 imported_count INTEGER NOT NULL DEFAULT 0,
 error_message VARCHAR(1000),
 started_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 finished_time TIMESTAMP WITH TIME ZONE,
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
