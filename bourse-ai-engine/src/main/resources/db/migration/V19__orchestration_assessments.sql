-- A persistent, bounded research pipeline. No market provider is called by this table.
-- A candle is the idempotency key: one assessment per asset/observed daily close.
CREATE TABLE orchestration_assessments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_id BIGINT NOT NULL REFERENCES assets(id),
 candle_time TIMESTAMP WITH TIME ZONE NOT NULL,
 status VARCHAR(24) NOT NULL CHECK (status IN ('RUNNING','SUCCEEDED','PARTIAL','DEFERRED','FAILED')),
 attempts INT NOT NULL DEFAULT 0 CHECK (attempts >= 0),
 lease_until TIMESTAMP WITH TIME ZONE,
 next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 quality_status VARCHAR(24),
 scoring_status VARCHAR(64),
 regime_status VARCHAR(64),
 alerts_triggered INT NOT NULL DEFAULT 0,
 error_code VARCHAR(60),
 started_at TIMESTAMP WITH TIME ZONE,
 finished_at TIMESTAMP WITH TIME ZONE,
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_orchestration_asset_candle UNIQUE(asset_id,candle_time)
);
CREATE INDEX idx_orchestration_due ON orchestration_assessments(status,next_attempt_at);
CREATE INDEX idx_orchestration_asset ON orchestration_assessments(asset_id,candle_time DESC);
-- Transaction-only gate for concurrent enqueue and claims, never held across HTTP/ML work.
CREATE TABLE orchestration_guard(id INT PRIMARY KEY CHECK(id=1));
