CREATE TABLE information_ai_analyses (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job_id BIGINT NOT NULL UNIQUE REFERENCES information_ai_jobs(id),
 content_id BIGINT NOT NULL REFERENCES information_contents(id),
 result_json TEXT NOT NULL,
 analyzed_characters INTEGER NOT NULL,
 review_status VARCHAR(16) NOT NULL DEFAULT 'PROPOSED' CHECK(review_status IN ('PROPOSED','APPROVED','REJECTED')),
 review_reason VARCHAR(1000),
 reviewed_at TIMESTAMP WITH TIME ZONE,
 created_time TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE information_ai_impacts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 analysis_id BIGINT NOT NULL REFERENCES information_ai_analyses(id),
 event_key VARCHAR(160) NOT NULL,
 event_group VARCHAR(160) NOT NULL,
 asset_id BIGINT NOT NULL REFERENCES assets(id),
 horizon VARCHAR(8) NOT NULL CHECK(horizon IN ('DAY','MONTH','YEAR')),
 direction VARCHAR(12) NOT NULL CHECK(direction IN ('POSITIVE','NEGATIVE','MIXED','UNKNOWN')),
 proposed_score NUMERIC(8,4),
 explanation VARCHAR(2000) NOT NULL,
 exact_quote VARCHAR(2000) NOT NULL,
 UNIQUE(analysis_id,event_key,asset_id,horizon)
);
