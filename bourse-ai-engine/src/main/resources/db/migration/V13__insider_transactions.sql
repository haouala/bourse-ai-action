-- SEC Form 4 transaction ledger: source-grounded, deduplicated by filing and transaction index.
CREATE TABLE insider_transactions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_id BIGINT NOT NULL REFERENCES assets(id),
 issuer_cik BIGINT NOT NULL,
 accession_number VARCHAR(32) NOT NULL,
 transaction_index INTEGER NOT NULL,
 owner_name VARCHAR(255) NOT NULL,
 owner_cik BIGINT,
 officer BOOLEAN NOT NULL DEFAULT FALSE,
 director BOOLEAN NOT NULL DEFAULT FALSE,
 ten_percent_owner BOOLEAN NOT NULL DEFAULT FALSE,
 security_title VARCHAR(255),
 transaction_date DATE NOT NULL,
 filed_date DATE NOT NULL,
 transaction_code VARCHAR(4) NOT NULL,
 acquired_disposed CHAR(1) NOT NULL CHECK(acquired_disposed IN ('A','D')),
 shares NUMERIC(30,8) NOT NULL CHECK(shares>=0),
 price_per_share NUMERIC(30,8),
 shares_owned_after NUMERIC(30,8),
 direct_indirect VARCHAR(8),
 is_derivative BOOLEAN NOT NULL DEFAULT FALSE,
 is_amendment BOOLEAN NOT NULL DEFAULT FALSE,
 footnote_present BOOLEAN NOT NULL DEFAULT FALSE,
 source_url VARCHAR(1000) NOT NULL,
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_insider_transaction UNIQUE(asset_id,accession_number,owner_name,transaction_index)
);
CREATE INDEX idx_insider_asset_date ON insider_transactions(asset_id,transaction_date DESC);
CREATE INDEX idx_insider_owner_date ON insider_transactions(owner_name,transaction_date DESC);
