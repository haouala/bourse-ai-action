-- Never mix sources silently: market_candles is the selected analytical series;
-- provider_price_observations retains each source separately for reconciliation.
CREATE TABLE asset_provider_symbols (
 asset_id BIGINT NOT NULL REFERENCES assets(id),
 provider VARCHAR(40) NOT NULL,
 provider_symbol VARCHAR(80) NOT NULL,
 exchange_mic VARCHAR(12),
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT pk_asset_provider_symbols PRIMARY KEY(asset_id,provider)
);
CREATE TABLE provider_price_observations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_id BIGINT NOT NULL REFERENCES assets(id),
 provider VARCHAR(40) NOT NULL,
 provider_symbol VARCHAR(80) NOT NULL,
 timeframe VARCHAR(8) NOT NULL,
 open_time TIMESTAMP WITH TIME ZONE NOT NULL,
 open_price NUMERIC(24,10) NOT NULL,
 high_price NUMERIC(24,10) NOT NULL,
 low_price NUMERIC(24,10) NOT NULL,
 close_price NUMERIC(24,10) NOT NULL,
 volume NUMERIC(28,8) NOT NULL,
 currency VARCHAR(3) NOT NULL,
 price_adjustment VARCHAR(30) NOT NULL DEFAULT 'UNSPECIFIED',
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_provider_observation UNIQUE(asset_id,provider,timeframe,open_time)
);
CREATE INDEX idx_observations_asset_time ON provider_price_observations(asset_id,open_time DESC);
