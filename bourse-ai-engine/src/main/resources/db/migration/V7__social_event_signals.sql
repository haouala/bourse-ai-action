CREATE TABLE social_api_reservations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id BIGINT NOT NULL REFERENCES social_actors(id),
 month_key VARCHAR(7) NOT NULL,
 reserved_posts INTEGER NOT NULL CHECK (reserved_posts>0),
 fetched_posts INTEGER,
 reserved_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_social_budget ON social_api_reservations(month_key);
