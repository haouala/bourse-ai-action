-- Scores are explainable review signals, never broker orders or calibrated probabilities.
CREATE TABLE social_actors (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 display_name VARCHAR(160) NOT NULL,
 role_label VARCHAR(160) NOT NULL,
 platform VARCHAR(24) NOT NULL,
 account_id VARCHAR(100) NOT NULL,
 identity_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
 identity_evidence_url VARCHAR(1500),
 last_post_id VARCHAR(24),
 pending_page_token VARCHAR(2000),
 pending_high_water_id VARCHAR(24),
 last_sync_at TIMESTAMP WITH TIME ZONE,
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(platform,account_id)
);
CREATE TABLE actor_influence_profiles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id BIGINT NOT NULL REFERENCES social_actors(id),
 topic VARCHAR(30) NOT NULL,
 authority_score INTEGER NOT NULL CHECK (authority_score BETWEEN 0 AND 100),
 valid_from TIMESTAMP WITH TIME ZONE NOT NULL,
 valid_until TIMESTAMP WITH TIME ZONE,
 rationale VARCHAR(1500) NOT NULL,
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (valid_until IS NULL OR valid_until>valid_from)
);
CREATE INDEX idx_actor_topic ON actor_influence_profiles(actor_id,topic,valid_from);
CREATE TABLE social_publications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id BIGINT NOT NULL REFERENCES social_actors(id),
 external_id VARCHAR(100) NOT NULL,
 content TEXT NOT NULL,
 source_url VARCHAR(1500) NOT NULL,
 published_at TIMESTAMP WITH TIME ZONE NOT NULL,
 collected_at TIMESTAMP WITH TIME ZONE NOT NULL,
 retracted BOOLEAN NOT NULL DEFAULT FALSE,
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(actor_id,external_id)
);
CREATE TABLE social_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 canonical_key VARCHAR(180) NOT NULL UNIQUE,
 title VARCHAR(300) NOT NULL,
 topic VARCHAR(30) NOT NULL,
 event_kind VARCHAR(24) NOT NULL,
 confirmation VARCHAR(24) NOT NULL,
 evidence_url VARCHAR(1500) NOT NULL,
 retracted BOOLEAN NOT NULL DEFAULT FALSE,
 revision INTEGER NOT NULL DEFAULT 1,
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE social_event_publications (
 event_id BIGINT NOT NULL REFERENCES social_events(id),
 publication_id BIGINT NOT NULL REFERENCES social_publications(id),
 PRIMARY KEY(event_id,publication_id)
);
CREATE TABLE social_asset_assessments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_id BIGINT NOT NULL REFERENCES social_events(id),
 asset_id BIGINT NOT NULL REFERENCES assets(id),
 direction VARCHAR(12) NOT NULL CHECK (direction IN ('POSITIVE','NEGATIVE','MIXED','UNKNOWN')),
 materiality INTEGER NOT NULL CHECK (materiality BETWEEN 0 AND 100),
 relevance INTEGER NOT NULL CHECK (relevance BETWEEN 0 AND 100),
 novelty INTEGER NOT NULL CHECK (novelty BETWEEN 0 AND 100),
 analyst_confidence INTEGER NOT NULL CHECK (analyst_confidence BETWEEN 0 AND 100),
 horizon VARCHAR(12) NOT NULL CHECK (horizon IN ('INTRADAY','DAYS','MONTHS','YEARS')),
 rationale VARCHAR(2000) NOT NULL,
 assessed_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(event_id,asset_id)
);
CREATE TABLE social_impact_scores (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 assessment_id BIGINT NOT NULL REFERENCES social_asset_assessments(id),
 event_revision INTEGER NOT NULL,
 scored_at TIMESTAMP WITH TIME ZONE NOT NULL,
 authority_score INTEGER NOT NULL,
 potential_impact NUMERIC(8,4) NOT NULL,
 confidence_score INTEGER NOT NULL,
 signed_score NUMERIC(8,4),
 method VARCHAR(48) NOT NULL,
 input_snapshot TEXT NOT NULL,
 review_only BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_social_scores ON social_impact_scores(assessment_id,scored_at DESC,id DESC);
CREATE TABLE social_api_guard (id INTEGER PRIMARY KEY);
