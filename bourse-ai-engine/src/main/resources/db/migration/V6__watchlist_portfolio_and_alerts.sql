-- Single-owner, long-only portfolio groundwork; no broker order execution.
CREATE TABLE watchlist_guard (id INTEGER PRIMARY KEY);
INSERT INTO watchlist_guard(id) VALUES (1);
CREATE TABLE watchlist (
 asset_id BIGINT PRIMARY KEY REFERENCES assets(id),
 provider_symbol VARCHAR(80) NOT NULL,
 region VARCHAR(12) NOT NULL CHECK (region IN ('US','EU','GLOBAL')),
 market_zone VARCHAR(80) NOT NULL,
 session_open VARCHAR(5) NOT NULL,
 session_close VARCHAR(5) NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE market_sync_tasks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_id BIGINT NOT NULL REFERENCES assets(id),
 timeframe VARCHAR(8) NOT NULL,
 slot_time TIMESTAMP WITH TIME ZONE NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 attempts INTEGER NOT NULL DEFAULT 0,
 next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
 lease_until TIMESTAMP WITH TIME ZONE,
 error_code VARCHAR(80),
 imported_count INTEGER NOT NULL DEFAULT 0,
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_sync_slot UNIQUE(asset_id,timeframe,slot_time),
 CONSTRAINT ck_sync_timeframe CHECK (timeframe IN ('15m','30m','1h','1d')),
 CONSTRAINT ck_sync_status CHECK (status IN ('PENDING','RUNNING','DEFERRED','SUCCEEDED','FAILED'))
);
CREATE INDEX idx_sync_pending ON market_sync_tasks(status,next_attempt_at);
CREATE TABLE portfolios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 base_currency VARCHAR(3) NOT NULL,
 initial_capital NUMERIC(24,8) NOT NULL CHECK (initial_capital>0),
 max_loss_amount NUMERIC(24,8) NOT NULL CHECK (max_loss_amount>0 AND max_loss_amount<=initial_capital),
 risk_latched BOOLEAN NOT NULL DEFAULT FALSE,
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE positions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 portfolio_id BIGINT NOT NULL REFERENCES portfolios(id),
 asset_id BIGINT NOT NULL REFERENCES assets(id),
 quantity NUMERIC(28,8) NOT NULL CHECK (quantity>=0),
 average_entry_quote NUMERIC(24,10) NOT NULL CHECK (average_entry_quote>0),
 remaining_cost_base NUMERIC(24,8) NOT NULL CHECK (remaining_cost_base>=0),
 horizon VARCHAR(12) NOT NULL CHECK (horizon IN ('SHORT','MEDIUM','LONG')),
 signal_timeframe VARCHAR(8) NOT NULL CHECK (signal_timeframe IN ('15m','30m','1h','1d')),
 opened_at TIMESTAMP WITH TIME ZONE NOT NULL,
 status VARCHAR(12) NOT NULL CHECK (status IN ('OPEN','CLOSED')),
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_positions_portfolio ON positions(portfolio_id,status);
CREATE TABLE position_trades (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 position_id BIGINT NOT NULL REFERENCES positions(id),
 portfolio_id BIGINT NOT NULL REFERENCES portfolios(id),
 client_order_id VARCHAR(80) NOT NULL,
 side VARCHAR(4) NOT NULL CHECK (side IN ('BUY','SELL')),
 quantity NUMERIC(28,8) NOT NULL CHECK (quantity>0),
 price_quote NUMERIC(24,10) NOT NULL CHECK (price_quote>0),
 fees_quote NUMERIC(24,10) NOT NULL CHECK (fees_quote>=0),
 fx_to_base NUMERIC(24,10) NOT NULL CHECK (fx_to_base>0),
 cash_delta_base NUMERIC(24,8) NOT NULL,
 realized_pnl_base NUMERIC(24,8) NOT NULL DEFAULT 0,
 executed_at TIMESTAMP WITH TIME ZONE NOT NULL,
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_portfolio_trade UNIQUE(portfolio_id,client_order_id)
);
CREATE TABLE position_marks (
 position_id BIGINT PRIMARY KEY REFERENCES positions(id),
 price_quote NUMERIC(24,10) NOT NULL CHECK (price_quote>0),
 fx_to_base NUMERIC(24,10) NOT NULL CHECK (fx_to_base>0),
 observed_at TIMESTAMP WITH TIME ZONE NOT NULL,
 source VARCHAR(64) NOT NULL,
 updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE portfolio_risk_snapshots (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 portfolio_id BIGINT NOT NULL REFERENCES portfolios(id),
 evaluated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 status VARCHAR(32) NOT NULL,
 cash_base NUMERIC(24,8) NOT NULL,
 known_equity_base NUMERIC(24,8) NOT NULL,
 loss_base NUMERIC(24,8),
 missing_marks INTEGER NOT NULL,
 stale_marks INTEGER NOT NULL,
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_risk_snapshots ON portfolio_risk_snapshots(portfolio_id,evaluated_at DESC);
CREATE TABLE trade_alerts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 portfolio_id BIGINT NOT NULL REFERENCES portfolios(id),
 position_id BIGINT REFERENCES positions(id),
 event_key VARCHAR(180) NOT NULL UNIQUE,
 alert_type VARCHAR(40) NOT NULL,
 message VARCHAR(1500) NOT NULL,
 data_time TIMESTAMP WITH TIME ZONE NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW','ACKNOWLEDGED')),
 created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_trade_alerts_pending ON trade_alerts(portfolio_id,status,created_time DESC);
